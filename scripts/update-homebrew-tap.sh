#!/usr/bin/env bash
# Regenerate the dadrock formula and the dadrock-desktop cask in
# vincentarelbundock/homebrew-tap for a released tag. Called by
# .github/workflows/update-homebrew-tap.yml once release-desktop.yml has
# published the macOS disk images.
#
# The formula builds the CLI from the tagged source, as calepin's does. The
# cask cannot: an .app bundle is not something Homebrew builds, so it points at
# the release's disk images and its hashes have to match those exact assets.
# release-desktop.yml publishes a .sha256 beside each one, so we use that and
# only fall back to hashing the image ourselves if the checksum is missing.
#
# A missing disk image skips the cask with a warning rather than failing, so a
# broken desktop build does not also hold back the CLI formula.
set -euo pipefail

: "${HOMEBREW_TAP_GITHUB_TOKEN:?HOMEBREW_TAP_GITHUB_TOKEN is required}"

tag="${DADROCK_RELEASE_TAG:-${GITHUB_REF_NAME:-}}"
if [[ -z "${tag}" ]]; then
  tag="$(git describe --tags --exact-match)"
fi

case "${tag}" in
  v*) ;;
  *)
    echo "expected a v-prefixed release tag, got: ${tag}" >&2
    exit 1
    ;;
esac

version="${tag#v}"
repo_url="https://github.com/vincentarelbundock/dadr"
source_url="${repo_url}/archive/refs/tags/${tag}.tar.gz"
tmpdir="$(mktemp -d)"
trap 'rm -rf "${tmpdir}"' EXIT

sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | cut -d " " -f 1
  else
    shasum -a 256 "$1" | cut -d " " -f 1
  fi
}

archive="${tmpdir}/dadr-${tag}.tar.gz"
curl -fsSL "${source_url}" -o "${archive}"
sha256="$(sha256_of "${archive}")"

# Prints the sha256 of one macOS disk image, or nothing if the release does
# not have it.
dmg_sha256() {
  local asset="dadrock-desktop-$1-apple-darwin.dmg"
  local url="${repo_url}/releases/download/${tag}/${asset}"
  local hash=""
  if curl -fsSL "${url}.sha256" -o "${tmpdir}/${asset}.sha256" 2>/dev/null; then
    hash="$(cut -d " " -f 1 "${tmpdir}/${asset}.sha256")"
  fi
  if ! [[ "${hash}" =~ ^[0-9a-f]{64}$ ]] &&
     curl -fsSL "${url}" -o "${tmpdir}/${asset}" 2>/dev/null; then
    echo "no usable checksum asset; hashing ${asset} instead" >&2
    hash="$(sha256_of "${tmpdir}/${asset}")"
  fi
  if [[ "${hash}" =~ ^[0-9a-f]{64}$ ]]; then
    printf '%s' "${hash}"
  fi
}

arm_sha256="$(dmg_sha256 aarch64)"
intel_sha256="$(dmg_sha256 x86_64)"

tap_dir="${tmpdir}/homebrew-tap"
git clone "https://x-access-token:${HOMEBREW_TAP_GITHUB_TOKEN}@github.com/vincentarelbundock/homebrew-tap.git" "${tap_dir}"
cd "${tap_dir}"

mkdir -p Formula
cat > Formula/dadrock.rb <<FORMULA
# typed: false
# frozen_string_literal: true

# This file was generated by dadr's release workflow. DO NOT EDIT.
class Dadrock < Formula
  desc "Record the decisions behind a data analysis as reviewable Markdown"
  homepage "https://vincentarelbundock.github.io/dadr"
  url "${source_url}"
  sha256 "${sha256}"
  license any_of: ["MIT", "Apache-2.0"]

  depends_on "bun" => :build
  depends_on "rust" => :build

  def install
    # build.rs embeds the web UI that \`dadrock preview\` serves, and needs Bun
    # to build it. Without this it would quietly fall back to a binary whose
    # preview has no UI.
    ENV["DADROCK_REQUIRE_JS_BUILD"] = "1"
    system "cargo", "install", *std_cargo_args(path: "crates/dadrock")
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/dadrock --version")
  end
end
FORMULA
git add Formula/dadrock.rb

if [[ -n "${arm_sha256}" && -n "${intel_sha256}" ]]; then
  # The release workflow notarizes only when the Apple signing secrets are
  # set, and update-homebrew-tap.yml passes that state on. An app that is not
  # notarized is blocked by Gatekeeper the first time it opens, so the cask
  # says so rather than leaving people with an unexplained refusal.
  caveats=""
  if [[ "${DADROCK_MACOS_NOTARIZED:-false}" != "true" ]]; then
    caveats="$(cat <<'CAVEATS'

  caveats <<~EOS
    Dadrock is not notarized by Apple yet, so macOS blocks it the first time
    it opens. To allow it, open System Settings > Privacy & Security and click
    "Open Anyway", or run:
      xattr -dr com.apple.quarantine "#{appdir}/Dadrock.app"
  EOS
CAVEATS
)"
  fi

  mkdir -p Casks
  cat > Casks/dadrock-desktop.rb <<CASK
# typed: false
# frozen_string_literal: true

# This file was generated by dadr's release workflow. DO NOT EDIT.
cask "dadrock-desktop" do
  arch arm: "aarch64", intel: "x86_64"

  version "${version}"
  sha256 arm:   "${arm_sha256}",
         intel: "${intel_sha256}"

  url "${repo_url}/releases/download/v#{version}/dadrock-desktop-#{arch}-apple-darwin.dmg"
  name "Dadrock"
  desc "Desktop app for reviewing Data Analysis Decision Records"
  homepage "https://vincentarelbundock.github.io/dadr"

  # The web UI needs Safari 16.4 or newer (Tailwind 4, oklch colours), and
  # WKWebView is the system Safari; 16.4 is not available before Big Sur.
  depends_on macos: ">= :big_sur"

  app "Dadrock.app"

  zap trash: [
    "~/Library/Application Support/com.arelbundock.dadrock",
    "~/Library/Caches/com.arelbundock.dadrock",
    "~/Library/Saved Application State/com.arelbundock.dadrock.savedState",
    "~/Library/WebKit/com.arelbundock.dadrock",
  ]
${caveats}
end
CASK
  git add Casks/dadrock-desktop.rb
else
  echo "::warning::${tag} has no complete set of dadrock-desktop disk images; the cask was left as it was"
fi

if git diff --cached --quiet; then
  echo "Homebrew tap already up to date"
  exit 0
fi

git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
git commit -m "Update dadrock to ${tag}"
git push origin HEAD:main
