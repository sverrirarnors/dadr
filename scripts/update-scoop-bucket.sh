#!/usr/bin/env bash
set -euo pipefail

# Regenerate the dadrock and dadrock-desktop manifests in
# vincentarelbundock/scoop-bucket for a released tag. Called by
# .github/workflows/update-scoop-bucket.yml once release-desktop.yml has
# published the Windows desktop archive.
#
# Both manifests point at prebuilt zips rather than building from source, so
# each hash has to match the exact asset. cargo-dist publishes a `.sha256`
# next to the CLI archive and release-desktop.yml does the same for the
# desktop one, so we use those and only fall back to hashing the archive
# ourselves if the checksum asset is missing.
#
# A missing desktop archive skips that manifest with a warning rather than
# failing, so a broken desktop build does not also hold back the CLI.

: "${SCOOP_BUCKET_GITHUB_TOKEN:?SCOOP_BUCKET_GITHUB_TOKEN is required}"

tag="${DADROCK_RELEASE_TAG:-${GITHUB_REF_NAME:-}}"
if [[ -z "${tag}" ]]; then
  tag="$(git describe --tags --exact-match)"
fi

case "${tag}" in
  v*) ;;
  *)
    echo "expected a v-prefixed release tag, got: ${tag}" >&2
    exit 1
    ;;
esac

version="${tag#v}"
repo_url="https://github.com/vincentarelbundock/dadr"

tmpdir="$(mktemp -d)"
trap 'rm -rf "${tmpdir}"' EXIT

# Prints the sha256 of one release asset, or nothing if the release does not
# have it.
asset_sha256() {
  local asset="$1"
  local url="${repo_url}/releases/download/${tag}/${asset}"
  local hash=""
  if curl -fsSL "${url}.sha256" -o "${tmpdir}/${asset}.sha256" 2>/dev/null; then
    # cargo-dist writes "<hash> *<filename>", sha256sum "<hash>  <filename>".
    hash="$(cut -d " " -f 1 "${tmpdir}/${asset}.sha256")"
  fi
  if ! [[ "${hash}" =~ ^[0-9a-f]{64}$ ]] &&
     curl -fsSL "${url}" -o "${tmpdir}/${asset}" 2>/dev/null; then
    echo "no usable checksum asset; hashing ${asset} instead" >&2
    if command -v sha256sum >/dev/null 2>&1; then
      hash="$(sha256sum "${tmpdir}/${asset}" | cut -d " " -f 1)"
    else
      hash="$(shasum -a 256 "${tmpdir}/${asset}" | cut -d " " -f 1)"
    fi
  fi
  if [[ "${hash}" =~ ^[0-9a-f]{64}$ ]]; then
    printf '%s' "${hash}"
  fi
}

cli_archive="dadrock-x86_64-pc-windows-msvc.zip"
cli_sha256="$(asset_sha256 "${cli_archive}")"
if [[ -z "${cli_sha256}" ]]; then
  echo "could not determine a sha256 for ${cli_archive}" >&2
  exit 1
fi

desktop_archive="dadrock-desktop-x86_64-pc-windows-msvc.zip"
desktop_sha256="$(asset_sha256 "${desktop_archive}")"

bucket_dir="${tmpdir}/scoop-bucket"
git clone "https://x-access-token:${SCOOP_BUCKET_GITHUB_TOKEN}@github.com/vincentarelbundock/scoop-bucket.git" "${bucket_dir}"
cd "${bucket_dir}"

mkdir -p bucket
cat > bucket/dadrock.json <<MANIFEST
{
    "##": "This file was generated by dadr's release workflow. DO NOT EDIT.",
    "version": "${version}",
    "description": "Data Analysis Decision Records: record the choices behind an empirical analysis, and review them in a local web UI.",
    "homepage": "https://vincentarelbundock.github.io/dadr",
    "license": "MIT|Apache-2.0",
    "architecture": {
        "64bit": {
            "url": "${repo_url}/releases/download/${tag}/${cli_archive}",
            "hash": "${cli_sha256}"
        }
    },
    "bin": "dadrock.exe",
    "checkver": {
        "github": "${repo_url}"
    },
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "${repo_url}/releases/download/v\$version/${cli_archive}"
            }
        },
        "hash": {
            "url": "\$url.sha256"
        }
    },
    "notes": [
        "Scoop owns this copy of dadrock. Upgrade with: scoop update dadrock"
    ]
}
MANIFEST
git add bucket/dadrock.json

if [[ -n "${desktop_sha256}" ]]; then
  # The zip carries its own dadrock.exe beside dadrock-desktop.exe, which the
  # app finds there, so this manifest does not depend on the CLI one. Only the
  # app is put on PATH; the CLI manifest owns the `dadrock` shim.
  cat > bucket/dadrock-desktop.json <<MANIFEST
{
    "##": "This file was generated by dadr's release workflow. DO NOT EDIT.",
    "version": "${version}",
    "description": "Desktop app for reviewing Data Analysis Decision Records in a native window.",
    "homepage": "https://vincentarelbundock.github.io/dadr",
    "license": "MIT|Apache-2.0",
    "architecture": {
        "64bit": {
            "url": "${repo_url}/releases/download/${tag}/${desktop_archive}",
            "hash": "${desktop_sha256}"
        }
    },
    "bin": "dadrock-desktop.exe",
    "shortcuts": [
        [
            "dadrock-desktop.exe",
            "Dadrock"
        ]
    ],
    "checkver": {
        "github": "${repo_url}"
    },
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "${repo_url}/releases/download/v\$version/${desktop_archive}"
            }
        },
        "hash": {
            "url": "\$url.sha256"
        }
    },
    "notes": [
        "Dadrock needs the Microsoft Edge WebView2 Runtime, which Windows 10 and 11 normally include. If the window stays blank, install it from https://developer.microsoft.com/microsoft-edge/webview2/",
        "Scoop owns this copy of Dadrock. Upgrade with: scoop update dadrock-desktop"
    ]
}
MANIFEST
  git add bucket/dadrock-desktop.json
else
  echo "::warning::${tag} has no ${desktop_archive}; the dadrock-desktop manifest was left as it was"
fi

if git diff --cached --quiet; then
  echo "Scoop manifests already up to date"
  exit 0
fi

git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
git commit -m "Update dadrock manifests to ${tag}"
git push origin HEAD:main
