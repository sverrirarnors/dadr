#!/usr/bin/env python3
"""Splice `dadrock gen-cli-docs` output into the command-line page.

Reads the clap-markdown output on stdin and rearranges it for reading: a
"Commands" section with one short table per group, then one section per
top-level command (in table order) with its subcommands nested under it. The
"Arguments:", "Options:" and "Subcommands:" headings become bold labels so
they stay out of the table of contents. The result replaces whatever is
between the two marker comments in the target file.
"""

import re
import sys
from pathlib import Path

START = "<!-- cli-docs:start -->"
END = "<!-- cli-docs:end -->"

# Top-level commands by group, in reading order. A command missing here lands
# in "Other", so a new command still shows up before this list is updated.
GROUPS = [
    ("Projects", ["init", "demo", "preview", "config", "dir"]),
    ("Records", ["new", "list", "accept", "reject", "supersede", "status"]),
    ("Validation", ["validate", "tags"]),
    ("Agents", ["agent", "task", "mcp"]),
    ("Help", ["help", "commands", "completions"]),
]

HEADING = re.compile(r"^## `dadrock(?: (.+))?`$")
LABEL = re.compile(r"^#+ \*\*(.+):\*\*$")
SUBCOMMAND = re.compile(r"^\* `([^`]+)` — ")


def anchor(name: str) -> str:
    return "#dadrock-" + name.replace(" ", "-")


def parse(markdown: str) -> dict[str, list[str]]:
    """Map each command ("" for the root, "validate records", ...) to its body."""
    sections: dict[str, list[str]] = {}
    current = None
    for line in markdown.splitlines():
        if line.startswith("<hr/>"):
            break  # clap-markdown's "generated by" footer
        match = HEADING.match(line)
        if match:
            current = match.group(1) or ""
            sections[current] = []
        elif current is not None:
            sections[current].append(line)
    return sections


def summary(body: list[str]) -> str:
    return next((line.strip() for line in body if line.strip()), "")


def render_body(name: str, body: list[str]) -> list[str]:
    out = []
    in_subcommands = False
    for line in body:
        label = LABEL.match(line)
        if label:
            in_subcommands = label.group(1) == "Subcommands"
            line = f"**{label.group(1)}**"
        elif in_subcommands:
            sub = SUBCOMMAND.match(line)
            if sub:
                child = f"{name} {sub.group(1)}"
                line = line.replace(f"`{sub.group(1)}`", f"[`{sub.group(1)}`]({anchor(child)})", 1)
        out.append(line)
    return out


def render(sections: dict[str, list[str]]) -> str:
    top = [name for name in sections if name and " " not in name]
    grouped = [(title, [n for n in names if n in sections]) for title, names in GROUPS]
    known = {n for _, names in grouped for n in names}
    other = [n for n in top if n not in known]
    if other:
        grouped.append(("Other", other))

    out = ["## Commands", ""]
    for title, names in grouped:
        if not names:
            continue
        out += [f"**{title}**", "", "| Command | Description |", "|---|---|"]
        for name in names:
            out.append(f"| [`{name}`]({anchor(name)}) | {summary(sections[name])} |")
        out.append("")

    for _, names in grouped:
        for name in names:
            out += [f"## `dadrock {name}`", ""] + render_body(name, sections[name])
            for child in sections:
                if child.startswith(name + " "):
                    out += [f"### `dadrock {child}`", ""] + render_body(child, sections[child])

    text = "\n".join(out).strip("\n")
    return re.sub(r"\n{3,}", "\n\n", text) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: splice-cli-docs.py <target.md> < generated.md", file=sys.stderr)
        return 2
    target = Path(sys.argv[1])
    page = target.read_text()
    if START not in page or END not in page:
        print(f"{target}: missing {START} / {END} markers", file=sys.stderr)
        return 1
    generated = render(parse(sys.stdin.read()))
    head, rest = page.split(START, 1)
    _, tail = rest.split(END, 1)
    target.write_text(f"{head}{START}\n\n{generated}\n{END}{tail}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
